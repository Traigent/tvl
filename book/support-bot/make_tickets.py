#!/usr/bin/env python3
"""Generate tickets.jsonl: 200 SYNTHETIC support tickets for the TVL book.

Every ticket is invented by this seeded script. None comes from a real
customer, and none has any text: the fields below are all a simulated bot
needs. The output is deterministic: the same seed gives the same file.

    python book/support-bot/make_tickets.py            # rewrites tickets.jsonl
    python book/support-bot/make_tickets.py --check    # fails if the file differs
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

SEED = 20261017
N_TICKETS = 200
N_TUNING = 60  # the rest (140) is the evaluation split

CATEGORIES = ["billing", "shipping", "account", "technical", "returns"]
CATEGORY_WEIGHTS = [0.22, 0.22, 0.18, 0.20, 0.18]
DIFFICULTIES = ["easy", "medium", "hard"]
DIFFICULTY_WEIGHTS = [0.45, 0.35, 0.20]
# Chance that a ticket of this category needs a tool lookup (order, invoice, ...).
LOOKUP_PROBABILITY = {
    "billing": 0.60,
    "shipping": 0.85,
    "account": 0.50,
    "technical": 0.20,
    "returns": 0.55,
}

HEADER = {
    "_meta": {
        "synthetic": True,
        "note": (
            "SYNTHETIC DATA. These tickets were generated by make_tickets.py from a seeded "
            "random generator. They are not real customer tickets, and results computed on "
            "them say nothing about any real support bot."
        ),
        "generator": "book/support-bot/make_tickets.py",
        "seed": SEED,
        "n_tickets": N_TICKETS,
        "splits": {"tuning": N_TUNING, "eval": N_TICKETS - N_TUNING},
    }
}


def generate() -> list[dict]:
    rng = random.Random(SEED)
    split_of = ["tuning"] * N_TUNING + ["eval"] * (N_TICKETS - N_TUNING)
    rng.shuffle(split_of)
    tickets = []
    for i in range(N_TICKETS):
        category = rng.choices(CATEGORIES, CATEGORY_WEIGHTS)[0]
        difficulty = rng.choices(DIFFICULTIES, DIFFICULTY_WEIGHTS)[0]
        needs_lookup = rng.random() < LOOKUP_PROBABILITY[category]
        tickets.append(
            {
                "id": f"T-{i + 1:04d}",
                "category": category,
                "difficulty": difficulty,
                "needs_lookup": needs_lookup,
                "split": split_of[i],
                "synthetic": True,
            }
        )
    return tickets


def render() -> str:
    lines = [json.dumps(HEADER, sort_keys=True)]
    lines += [json.dumps(t, sort_keys=True) for t in generate()]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("tickets.jsonl"))
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
            print(f"{args.out} differs from the generator output", file=sys.stderr)
            return 1
        print(f"{args.out} matches the generator")
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({N_TICKETS} synthetic tickets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
