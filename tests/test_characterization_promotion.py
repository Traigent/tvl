def normalize(value):
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {"__class__": type(value).__name__, **normalize(dataclasses.asdict(value))}
    if isinstance(value, dict):
        return {k: normalize(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return type(value)(normalize(v) for v in value)
    if isinstance(value, bool) or value is None or isinstance(value, (str, int)):
        return value
    as_float = float(value)
    return "nan" if math.isnan(as_float) else as_float


def _samples(name, direction, epsilon, inc, cand, paired):
    return _test_from_samples(ObjectiveSpec(name=name, direction=direction, epsilon=epsilon), inc, cand, paired)


def _banded(band, cand_data, alpha):
    return _test_banded_objective(ObjectiveSpec(name="b", direction="maximize", epsilon=0.0, band=band), cand_data, alpha)


def _decide(spec):
    evidence = PromotionEvidence()
    for name, (kind, verdict) in spec.get("per_objective", {}).items():
        if kind == "band":
            evidence.per_objective[name] = BandedResult(name=name, verdict=verdict)
        else:
            evidence.per_objective[name] = ObjectiveResult(
                name=name, test_type="welch", n_incumbent=0, n_candidate=0,
                mean_incumbent=0.0, mean_candidate=0.0, delta=0.0, std_pooled=None,
                t_statistic=None, df=None, p_value_noninf=1.0, p_value_super=1.0,
                verdict=verdict,
            )
    for name, verdict in spec.get("chance", {}).items():
        evidence.chance_constraints[name] = ChanceResult(
            name=name, violations=0, trials=1, observed_rate=0.0, ci_lower=0.0,
            ci_upper=0.0, threshold=0.0, confidence=0.95, verdict=verdict,
        )
    for flag, value in spec.get("flags", {}).items():
        setattr(evidence, flag, value)
    return _make_decision(evidence)


