"""Frozen 1.3 wire bytes and conservative RFC 0004 format dispatch."""
from __future__ import annotations

import copy
from pathlib import Path

import pytest

from tvl.canonical import RuntimeClosedError, canonical_json_str
from tvl.runtime_compiler import compile_runtime_document
from tvl.runtime_projection import validate_projected_contract
from tvl.schema import runtime_contract_validator, runtime_local_validator
from tvl.yaml_safe import safe_load

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / 'conformance/cases/runtime/projection'


def compile_case(name='deploy-mode-closed', version=None):
    case = safe_load((CASES / f'{name}.yml').read_text())
    doc = copy.deepcopy(case['module'])
    if version is not None:
        doc['tvl_version'] = version
    return compile_runtime_document(
        doc, token_map_doc={'format': 'tvl-token-map/1', 'tokens': case['input']['token_map']},
    )[:2]


def test_13_compiles_to_frozen_130_canonical_bytes():
    # Generated with the compiler and schemas from bcd20f6dd2f4d5596d4e28fcbdc85252d17bc72d,
    # using deploy-mode-closed.yml's module/token map and default toolchain_version 1.3.0.
    # Includes digests and local defaults: this must not be regenerated by the compiler under test.
    contract, local = compile_case()
    for kind, actual in [('contract', contract), ('local', local)]:
        assert actual['format'] == f'tvl-runtime-{kind}/1'
        expected = ROOT / f'conformance/expected/runtime-1.3/deploy-mode-closed-{kind}.json'
        assert canonical_json_str(actual).encode() == expected.read_bytes()


@pytest.mark.parametrize('version', [None, '1.0', '1.1', '1.2', 1.2, '1.3'])
def test_legacy_module_without_runtime_keeps_130_compiled_version(version):
    case = safe_load((CASES / 'deploy-mode-closed.yml').read_text())
    doc = case['module']
    for key in ('tvl_version', 'requirements', 'monitors', 'responses'):
        doc.pop(key)
    if version is not None:
        doc['tvl_version'] = version
    contract, local, _ = compile_runtime_document(
        doc, token_map_doc={'format': 'tvl-token-map/1', 'tokens': case['input']['token_map']},
    )
    assert contract['tvl_version'] == local['tvl_version'] == '1.3'
    assert contract['format'] == 'tvl-runtime-contract/1'
    assert local['format'] == 'tvl-runtime-local/1'


@pytest.mark.parametrize('field', ['outcome', 'unknown_for', 'only_while', 'unless'])
def test_each_14_construct_alone_uses_v2(field):
    case = safe_load((CASES / 'outcome-and-guard-closed-enums.yml').read_text())
    doc = case['module']
    rules = doc['responses'][0]['rules']
    if field == 'outcome':
        page = {'id': 'outcome', 'trigger': {'rule': 'opt', 'event': 'optimize_failed'}, 'do': 'notify'}
    elif field == 'unknown_for':
        page = copy.deepcopy(rules[2])
    else:
        page = {'id': 'outcome', 'trigger': {'monitor': 'monitor_main', 'event': 'episode_opened'},
                'do': 'notify', field: copy.deepcopy(rules[1][field])}
    doc['responses'][0]['rules'] = [rules[0], page]
    contract, local, _ = compile_runtime_document(
        doc, token_map_doc={'format': 'tvl-token-map/1', 'tokens': case['input']['token_map']},
    )
    assert contract['format'] == 'tvl-runtime-contract/2'
    assert local['format'] == 'tvl-runtime-local/2'
    validate_projected_contract(contract)
    assert not list(runtime_local_validator(local['format']).iter_errors(local))


@pytest.mark.parametrize('has_runtime', [False, True])
def test_14_without_new_constructs_uses_v2_version_exception(has_runtime):
    case = safe_load((CASES / 'deploy-mode-closed.yml').read_text())
    doc = case['module']
    doc['tvl_version'] = '1.4'
    if not has_runtime:
        for key in ('requirements', 'monitors', 'responses'):
            doc.pop(key)
    contract, local, _ = compile_runtime_document(
        doc, token_map_doc={'format': 'tvl-token-map/1', 'tokens': case['input']['token_map']},
    )
    for kind, artifact in [('contract', contract), ('local', local)]:
        assert artifact['format'] == f'tvl-runtime-{kind}/2'
        assert artifact['tvl_version'] == '1.4'
    validate_projected_contract(contract)
    assert not list(runtime_local_validator(local['format']).iter_errors(local))


@pytest.mark.parametrize('kind', ['contract', 'local'])
@pytest.mark.parametrize('field', ['outcome', 'unknown_for', 'only_while', 'unless'])
def test_v1_refuses_each_14_field_even_with_13_version(kind, field):
    contract, local = compile_case()
    artifact = contract if kind == 'contract' else local
    rule = artifact['declarations']['responses'][0]['rules'][0]
    if field == 'outcome':
        rule['trigger'] = {'rule': 'opaque_rule_opt' if kind == 'contract' else 'opt', 'event': 'optimize_failed'}
    elif field == 'unknown_for':
        rule['trigger'].update(event='unknown_for', hours=6)
    else:
        rule[field] = []  # Even an empty 1.4 field must be refused, not silently ignored.
    factory = runtime_contract_validator if kind == 'contract' else runtime_local_validator
    assert list(factory(artifact['format']).iter_errors(artifact))
    if kind == 'contract':
        with pytest.raises(RuntimeClosedError, match='runtime_unsafe_egress'):
            validate_projected_contract(artifact)


