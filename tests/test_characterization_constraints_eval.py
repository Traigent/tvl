def normalize(value):
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {"__class__": type(value).__name__, **normalize(dataclasses.asdict(value))}
    if isinstance(value, dict):
        return {k: normalize(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return type(value)(normalize(v) for v in value)
    return value


def _atoms(dnf):
    return [[Atom(*atom) for atom in conj] for conj in dnf]


def _evaluate(domains, constraint_specs, assignments):
    compiled = CompiledConstraints(
        domains={d["path"]: Domain(**d) for d in domains},
        constraints=[
            StructuralConstraint(antecedent=_atoms(ante), consequent=_atoms(cons), raw=raw)
            for ante, cons, raw in constraint_specs
        ],
    )
    return evaluate_assignment(compiled, assignments)


def _create(domain):
    model = cp_model.CpModel()
    var = _create_variable(model, Domain(**domain))
    proto = model.Proto()
    return var.Name(), [list(v.domain) for v in proto.variables]


def _satisfiable(module, exact=True):
    compiled = compile_constraints(module)
    result = check_structural_satisfiable(compiled)
    if result["ok"] and not exact:
        report = evaluate_assignment(compiled, result["assignment"])
        assert report == {"domains": [], "constraints": []}, report
        return {"ok": True, "assignment_keys": sorted(result["assignment"])}
    return result


