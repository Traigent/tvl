_REAL_SOLVER = cp_model.CpSolver


def _assuming_solver(with_core, created):
    class _Solver:
        """Stand-in for an OR-Tools release that exposes SolveWithAssumptions."""

        def __init__(self):
            self._solver = _REAL_SOLVER()
            self.literals = []
            created.append(self)

        def SolveWithAssumptions(self, model, literals):
            self.literals = list(literals)
            model.AddAssumptions(literals)
            return self._solver.Solve(model)

        def Value(self, var):
            return self._solver.Value(var)

    if with_core:
        def core(self):
            return [lit for lit in self.literals if lit.Name() == "expr_2_3"]

        _Solver.SufficientAssumptionsForInfeasibility = core
    return _Solver


