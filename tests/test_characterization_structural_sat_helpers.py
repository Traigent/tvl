def test_assumption_solver_satisfiable(monkeypatch):
    created = []
    monkeypatch.setattr(cp_model, "CpSolver", _assuming_solver(True, created))
    module = _module([{"name": "n", "type": "int", "domain": {"range": [0, 5]}}], [{"expr": "n = 2"}])
    assert normalize(check_structural(module)) == {
        "__class__": "StructuralResult", "ok": True, "assignment": {"n": 2},
        "unsat_core": None, "core_metadata": None,
    }
    assert [lit.Name() for lit in created[0].literals] == ["expr_1_1"]


