def normalize(value):
    if isinstance(value, float) and math.isnan(value):
        return "nan"
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {"__class__": type(value).__name__, **normalize(dataclasses.asdict(value))}
    if isinstance(value, dict):
        return {k: normalize(v) for k, v in value.items()}
    if isinstance(value, list):
        return [normalize(v) for v in value]
    return value


def _module(tvars, structural):
    return {"tvars": tvars, "constraints": {"structural": structural}}


def _check(tvars, structural, exact=True):
    module = _module(tvars, structural)
    result = check_structural(module)
    if result.ok and not exact:
        expressions = build_structural_model(module).expressions
        assert all(_evaluate_expression(e, result.assignment) for e in expressions)
        return {"ok": True, "assignment_keys": sorted(result.assignment)}
    return result


def _integrate(clauses, literal, tvar_names):
    clause_objects = [[structural_sat.Condition(*c) for c in clause] for clause in clauses]
    return _integrate_literal(clause_objects, Literal(**literal), set(tvar_names))


