def test_pinned_case(case_id, fn, args, kwargs, expected):
    func = FUNCS[fn]
    args = copy.deepcopy(args)
    kwargs = copy.deepcopy(kwargs)
    if expected[0] == "raises":
        with pytest.raises(Exception) as info:
            func(*args, **kwargs)
