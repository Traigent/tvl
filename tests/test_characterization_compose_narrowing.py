def _compose_files(files, entry, validate_narrowing=True):
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp).resolve()
        for name, content in files.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            text = content if isinstance(content, str) else yaml.safe_dump(content, sort_keys=False)
            path.write_text(text, encoding="utf-8")
        try:
            return ("ok", compose(root / entry, validate_narrowing=validate_narrowing))
        except Exception as exc:  # noqa: BLE001 - pinned below
            return ("raises", type(exc).__name__, str(exc).replace(str(root), "<ROOT>"))


